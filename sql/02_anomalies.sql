-- ============================================================
-- Шаг 2. Демонстрация трёх аномалий «плохой» таблицы
-- Каждая демонстрация откатывается (ROLLBACK), данные не портятся
-- ============================================================

USE orders_norm_lab5;

SET autocommit = 0;

-- ------------------------------------------------------------
-- АНОМАЛИЯ 1: АНОМАЛИЯ ОБНОВЛЕНИЯ (UPDATE ANOMALY)
-- ------------------------------------------------------------
-- Клиент 101 «Иванов И. И.» встречается в 4 строках.
-- Чтобы исправить имя, придётся обновить ВСЕ эти строки.
-- Если обновить не все — в таблице останутся противоречивые данные.

SELECT COUNT(*) AS rows_of_customer_101
FROM orders_bad
WHERE customer_id = 101;

-- Придётся обновить сразу 4 строки одним запросом:
UPDATE orders_bad
SET customer_name = 'Иванов Иван Иванович'
WHERE customer_id = 101;

-- А если ошибиться и обновить только часть строк (только один заказ),
-- данные станут ПРОТИВОРЕЧИВЫМИ: у одного клиента два имени
UPDATE orders_bad
SET customer_name = 'Иванов И. И.'
WHERE customer_id = 101 AND order_id = 5001;

SELECT customer_id, customer_name, COUNT(*) AS cnt
FROM orders_bad
GROUP BY customer_id, customer_name;

ROLLBACK;  -- отменяем демо-изменения

-- ------------------------------------------------------------
-- АНОМАЛИЯ 2: АНОМАЛИЯ ВСТАВКИ (INSERT ANOMALY)
-- ------------------------------------------------------------
-- Нельзя добавить НОВОГО клиента, товар или классификацию,
-- пока нет заказа: приходится вставлять бессмысленные NULL
-- в несвязанные поля.

-- Попытка завести классификацию 303 «Мебель» без товара и заказа:
INSERT INTO orders_bad
    (order_id, order_date, customer_id, customer_name,
     product_id, product_name, price, class_id, class_name, quantity)
VALUES (NULL, NULL, NULL, NULL, NULL, NULL, NULL, 303, 'Мебель', NULL);

SELECT * FROM orders_bad WHERE class_id = 303;

ROLLBACK;  -- отменяем демо-вставку

-- ------------------------------------------------------------
-- АНОМАЛИЯ 3: АНОМАЛИЯ УДАЛЕНИЯ (DELETE ANOMALY)
-- ------------------------------------------------------------
-- Удалим заказ 5004 — единственный заказ клиента 103 «Сидорова А. А.».
-- Вместе с ним НЕОБРАТИМО теряется информация, что вообще
-- существует клиент 103.

DELETE FROM orders_bad
WHERE order_id = 5004;

-- Строк заказа 5004 больше нет:
SELECT * FROM orders_bad WHERE order_id = 5004;

-- Клиент 103 исчез из таблицы полностью:
SELECT DISTINCT customer_id, customer_name
FROM orders_bad
WHERE customer_id = 103;

ROLLBACK;  -- отменяем демо-удаление

-- Возвращаем автокоммит
SET autocommit = 1;

-- Итоговая проверка: данные на месте (ROLLBACK-и всё вернули)
SELECT * FROM orders_bad ORDER BY order_id, product_id;
